"""The parts and textures each game outfit takes from another outfit's folder of its fighter, for the Manager.

The game builds many outfits from others' parts: Ingrid Outfit 5 wears the head and hair of Outfit 2, most
Outfit 5s the hair of Outfit 1, and materials name other outfits' body and hair textures. The source is the
game itself: each outfit's costume scene (natives/stm/product/charparam/esf/esfNNN/esfNNNvVV.scn.20, which
mesh and material every part loads) and the material files it names (their textures).

Steps after a game update (REtool reads the game's paks; -forceExtract only reads, it changes nothing):
  1. python shared_outfit_parts.py scenes <scenes.list>
     REtool -sf6 -h <scenes.list> -x -skipUnknowns -noExtractDir -forceExtract <game>\\re_chunk_000.pak
     (from an empty folder, <x>; its exit code is 1 even when it worked)
  2. python shared_outfit_parts.py materials <x> <materials.list>, REtool again with that list into <x>
  3. python shared_outfit_parts.py cs <x> ..\\src\\SharedOutfitParts.Data.cs
"""
import os, re, sys

PAT = re.compile(rb'(?:[\x20-\x7e]\x00){6,}')
MODEL = re.compile(r'^@?product/model/esf/esf(\d{3})/(\d{3})/(?:(\d{2})/)?', re.I)
SCENE = re.compile(r'^esf(\d{3})v(\d{2})\.scn\.\d+$', re.I)
SUF = {"mesh": "230110883", "mdf2": "31"}


def strings(path):
    data = open(path, 'rb').read()
    return list(dict.fromkeys(m.group().decode('utf-16le') for m in PAT.finditer(data)))


def walk(root, kind):
    for base, _, names in os.walk(root):
        for n in names:
            if kind in n.lower():
                yield os.path.join(base, n)


def pak(ref):
    ref = ref.lstrip('@').lower()
    return "natives/stm/" + ref + "." + SUF.get(ref.rsplit('.', 1)[-1], "")


def cmd_scenes(out):
    lines = []
    for n in range(1, 60):
        for v in range(41):
            lines.append(f"natives/stm/product/charparam/esf/esf{n:03d}/esf{n:03d}v{v:02d}.scn.20")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print(len(lines), "scene paths")


def scenes(root):
    for p in walk(root, '.scn.'):
        m = SCENE.match(os.path.basename(p))
        if m and int(m.group(1)) < 100:   # esf101+ are not playable
            yield m.group(1), p


def cmd_materials(root, out):
    want = sorted({pak(s) for _, p in scenes(root) for s in strings(p) if MODEL.match(s) and s.lower().endswith('.mdf2')})
    open(out, "w", newline="\n").write("\n".join(want) + "\n")
    print(len(want), "material files")


def cmd_cs(root, out):
    mdfs = {}
    for p in walk(root, '.mdf2.'):
        mdfs[p[p.lower().index('natives'):].replace('\\', '/').lower()] = p
    table, worn = {}, {}
    for code, scn in sorted(scenes(root)):
        refs = [s for s in strings(scn) if MODEL.match(s)]
        body = next((MODEL.match(r).group(2) for r in refs if r.lower().endswith('.mesh')
                     and MODEL.match(r).group(3) == '01' and MODEL.match(r).group(2) != '000'), None)
        if body is None:
            continue
        parts, tex = set(), set()
        wears = {}
        for r in refs:
            m = MODEL.match(r)
            low = r.lower()
            if m.group(1) == code and m.group(3) and low.endswith('.mesh'):
                wears.setdefault(m.group(3), set()).add(m.group(2))
            if m.group(1) == code and m.group(3) and m.group(2) not in ('000', body) and low.endswith(('.mesh', '.mdf2')):
                parts.add(m.group(2) + "/" + m.group(3))
            if low.endswith('.mdf2'):
                p = mdfs.get(pak(r))
                if p is None:
                    sys.exit("material not extracted: " + r)
                for t in strings(p):
                    tm = MODEL.match(t)
                    if tm and t.lower().endswith('.tex') and tm.group(1) == code and tm.group(3) and tm.group(2) not in ('000', body):
                        tex.add(tm.group(2) + "/" + tm.group(3))
        entries = sorted(parts) + ["tex:" + t for t in sorted(tex - parts)]
        if entries:
            table[code + "/" + body] = entries
        worn[code + "/" + body] = ["%s:%s" % (p, f) for p, fs in sorted(wears.items()) for f in sorted(fs)]
    rows = "\n".join('            { "%s", new[] { %s } },' % (k, ", ".join('"%s"' % e for e in v)) for k, v in sorted(table.items()))
    worn_rows = "\n".join('            { "%s", new[] { %s } },' % (k, ", ".join('"%s"' % e for e in v)) for k, v in sorted(worn.items()))
    text = ("// Generated by manager/tools/shared_outfit_parts.py from the game's costume scenes and material files.\n"
            "// Do not edit by hand: run the tool again after a game update (its steps are in its header).\n"
            "using System;\nusing System.Collections.Generic;\n\nnamespace SlotsInstaller\n{\n"
            "    internal static partial class SharedOutfitParts\n    {\n"
            "        // \"<fighter>/<outfit folder>\" -> \"<folder>/<part>\" (that part's mesh or material: all its files) or\n"
            "        // \"tex:<folder>/<part>\" (textures there that the outfit's material files name).\n"
            "        private static readonly Dictionary<string, string[]> Borrowed = new Dictionary<string, string[]>(StringComparer.Ordinal)\n"
            "        {\n" + rows + "\n        };\n"
            "        // \"<fighter>/<outfit folder>\" -> \"<part>:<folder>\": the folders each part's meshes come from (000 = shared).\n"
            "        private static readonly Dictionary<string, string[]> Worn = new Dictionary<string, string[]>(StringComparer.Ordinal)\n"
            "        {\n" + worn_rows + "\n        };\n    }\n}\n")
    open(out, "w", encoding="utf-8", newline="\r\n").write(text)
    print(len(table), "outfits take parts or textures from another outfit's folder")


if __name__ == "__main__":
    a = sys.argv[1:]
    {"scenes": lambda: cmd_scenes(a[1]), "materials": lambda: cmd_materials(a[1], a[2]), "cs": lambda: cmd_cs(a[1], a[2])}[a[0]]()
